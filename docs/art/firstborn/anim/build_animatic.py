"""Builds the gate 3 animatic: every Animation's key poses, played at their real timing.

Run:  py docs/art/firstborn/anim/build_animatic.py
Writes previews/03-animatic.html (self-contained, opens from disk).

A key-pose animatic shows only keys, smears and holds, each held until the next one, at the
planned durations. In-betweens are posed in stage 4, after the timing is approved, so nothing
drawn is thrown away if the timing changes.
"""

import base64
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, HERE)

import brim  # noqa: E402
import egg  # noqa: E402
import emotes  # noqa: E402
import hatchling  # noqa: E402
import pixkit as px  # noqa: E402
import timing as T  # noqa: E402


def uri(grid):
    w, h = px.grid_size(grid)
    data = px.png_bytes(w, h, px.grid_to_rgba(grid, brim.PALETTE))
    return "data:image/png;base64," + base64.b64encode(data).decode()


def key_drawing(anim):
    """For each Frame, the index of the key, smear or posed hold it shows in a key-pose animatic."""
    out, last = [], None
    for i, f in enumerate(anim.frames):
        if f.kind != "inbetween" and f.pose is not None:
            last = i
        if last is None:
            raise ValueError(f"{anim.name}: starts with an in-between")
        out.append(last)
    return out


def build(anim, images):
    shows = key_drawing(anim)
    bases = {}
    for i in sorted(set(shows)):
        bases[i] = T.base(anim.frames[i].pose, f"{anim.name}[{i}]", anim.form)
    frames = []
    sched = T.schedule(anim)
    ms = T.ms_list([t for _, _, t in sched])
    for (i, flame, ticks), dur in zip(sched, ms):
        grid, info = bases[shows[i]]
        kind = anim.frames[i].flame_kind or anim.flame_kind
        if anim.form == "hatchling":
            grid = brim.overlay(grid, info, flame, kind)
        u = uri(grid)
        if u not in images:
            images[u] = len(images)
        frames.append({"img": images[u], "ms": dur, "sheet": i})
    sheet = []
    for i, f in enumerate(anim.frames):
        sheet.append({"kind": f.kind, "label": f.label, "ticks": f.ticks,
                      "posed": f.pose is not None})
    cell = (brim.EGG_CELL if anim.form == "egg" else (brim.CELL_W, brim.CELL_H))
    return {
        "name": anim.name, "form": anim.form, "once": anim.once, "note": anim.note, "speed": anim.speed,
        "cell": cell, "frames": frames, "sheet": sheet,
        "sheet_ms": T.ms_list([f.ticks for f in anim.frames]),
        "length_ms": sum(T.ms_list([f.ticks for f in anim.frames])),
        "exported": len(sched), "drawings": len(anim.frames),
    }


def write_sheets(forms, emote_list):
    """03-timing-sheets.md, generated from the same data as the animatic so the two can't disagree."""
    lines = ["# firstborn: timing sheets", "",
             "Generated by `anim/build_animatic.py` from `anim/egg.py`, `anim/hatchling.py` and `anim/emotes.py`.",
             "Edit those, not this file. One tick is 1/30 s. The ms column is what the manifest gets: the running",
             "total of ticks rounded down, so no Frame is ever late.", "",
             "Kinds: **key** is a main pose; **in-between** goes between keys and is posed in stage 4; **smear** is a",
             "stretched drawing for fast motion; **hold** keeps a pose still.", ""]
    for fm in forms:
        for a in fm["anims"]:
            plays = "meant to play once" if a["once"] else "loops"
            lines += [f"## {fm['form']} / {a['name']}", "",
                      f"{a['note']}", "",
                      f"{plays}; {a['length_ms'] / 1000:.2f} s; {a['drawings']} drawings, {a['exported']} exported Frames.",
                      "", "| # | Kind | What happens | Ticks | ms |", "|---|---|---|---|---|"]
            for i, (f, ms) in enumerate(zip(a["sheet"], a["sheet_ms"])):
                lines.append(f"| {i + 1} | {f['kind']} | {f['label']} | {f['ticks']} | {ms} |")
            lines.append("")
    for e in emote_list:
        lines += [f"## Emote / {e['name']}", "", f"{e['mode']}.", "", "| # | What happens | Ticks | ms |",
                  "|---|---|---|---|"]
        for i, (f, ms) in enumerate(zip(e["sheet"], e["sheet_ms"])):
            lines.append(f"| {i + 1} | {f['label']} | {f['ticks']} | {ms} |")
        lines.append("")
    with open(os.path.join(ROOT, "03-timing-sheets.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    t0 = time.perf_counter()
    images = {}
    forms = []
    for form, mod in (("egg", egg), ("hatchling", hatchling)):
        forms.append({"form": form, "anims": [build(a, images) for a in mod.ANIMATIONS]})
    emote_list = [{"name": n, "mode": m, "sheet": [{"label": l, "ticks": t} for l, t, _ in fr],
                   "sheet_ms": T.ms_list([t for _, t, _ in fr])} for n, m, fr in emotes.EMOTES]
    data = {"forms": forms, "emotes": emote_list, "images": [u for u, _ in sorted(images.items(), key=lambda kv: kv[1])]}
    with open(os.path.join(HERE, "animatic-page.html"), encoding="utf-8") as f:
        page = f.read()
    out = os.path.join(ROOT, "previews", "03-animatic.html")
    with open(out, "w", encoding="utf-8") as f:
        f.write(page.replace("/*DATA*/null", json.dumps(data)))
    write_sheets(forms, emote_list)
    n_draw = sum(a["drawings"] for fm in forms for a in fm["anims"])
    n_exp = sum(a["exported"] for fm in forms for a in fm["anims"])
    print(f"wrote {out}: {n_draw} drawings, {n_exp} exported Frames, {time.perf_counter() - t0:.1f} s")


if __name__ == "__main__":
    main()
